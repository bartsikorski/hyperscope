"""Palette tables from mandelscope's own code, to check that Hyperscope bakes its gradients the same way.
Writes tests/unit/data/palettes.json (the 24 gradients, each baked at 256 entries in sRGB) and
src/content/palettes.json (the gradient stops, copied verbatim, plus Hyperscope's discrete sets).

Run: python tools/hp/palette_vectors.py <path to a mandelscope checkout>
(mandelscope: github.com/bartsikorski/mandelscope, MIT; needs numpy)."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(sys.argv[1]).resolve()))
from mandelscope import palettes as ms  # noqa: E402

N = 256
root = Path(__file__).resolve().parents[2]

tables = {name: [[round(float(v), 12) for v in row] for row in ms.make_palette(name, N)] for name in ms.PALETTES}
(root / "tests/unit/data/palettes.json").write_text(json.dumps({"n": N, "tables": tables}, separators=(",", ":")) + "\n")

# Discrete sets for k-colourings (Hyperscope's own): colours in order, evenly spaced when a
# continuous source uses them as a gradient.
DISCRETE = {
    "Gilded tiles": ["#0b1f45", "#1f5a99", "#8fc3e8", "#b3651b", "#4a1d08"],
    "Escher": ["#e9dcbc", "#7b4a2e", "#c69a58", "#33402f", "#a5452e", "#6f8a72"],
    "Ink & paper": ["#f2ebdb", "#1c1b19", "#cbbfa6", "#55514a"],
    "Neon tiles": ["#120a3a", "#00d5ff", "#ff38c8", "#3a1a8c", "#e6fdff", "#06031a"],
}
out = {
    "source": "Gradients: mandelscope (github.com/bartsikorski/mandelscope, MIT), palettes.py, copied verbatim. "
              "Discrete sets: Hyperscope. Generated by tools/hp/palette_vectors.py.",
    "gradients": [{"name": name, "stops": None if stops is None else [[p, c] for p, c in stops]} for name, stops in ms.PALETTES.items()],
    "discrete": [{"name": name, "colours": cols} for name, cols in DISCRETE.items()],
}
# one palette per line, so diffs stay readable
lines = ["{", f' "source": {json.dumps(out["source"])},', ' "gradients": [']
lines += [f"  {json.dumps(g)}," for g in out["gradients"]]
lines[-1] = lines[-1].rstrip(",")
lines += [" ],", ' "discrete": [']
lines += [f"  {json.dumps(d)}," for d in out["discrete"]]
lines[-1] = lines[-1].rstrip(",")
lines += [" ]", "}"]
(root / "src/content/palettes.json").write_text("\n".join(lines) + "\n")
print(f"{len(tables)} gradients, {len(DISCRETE)} discrete sets")
