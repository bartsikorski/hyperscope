// Colourings of a triangle-group tiling as group maps.
//
// A mirror colouring with k colours sends each mirror reflection r_j to a permutation sigma_j of the
// colours. It is consistent with the tiling exactly when the group relations hold:
//   sigma_j^2 = id,   (sigma_1 sigma_2)^p = (sigma_1 sigma_3)^q = (sigma_2 sigma_3)^r = id.
// A point that folds with the mirror word j1, j2, ..., jK lies in the tile h T with h = r_j1 r_j2 ... r_jK,
// whose colour is sigma_j1(sigma_j2(...sigma_jK(c0))). Folding therefore accumulates
//   P <- P o sigma_j        (P starts at the camera's permutation, see below)
// and the colour is P(c0). Re-centering the camera by a symmetry continues the same accumulation along
// the re-centering word, so the picture keeps its colours (tested in colourings.test.ts).
//
// A chiral colouring is respected by the rotations only (design notes, step 14): permutations alpha of
// a = s1 s2 (about P) and beta of b = s3 s1 (about Q) with alpha^p = beta^q = (alpha beta)^r = id. It
// colours kites, the triangle T and its mirror image across side 1: the kite of an even h gets
// pi(h)(c0). The fold word is read in pairs, each pair a rotation (pairPerms); an odd word's last
// mirror pairs with side 1, since its triangle lies in the kite of h s1.
//
// Both kinds are found by Sims' low-index subgroup method (lowIndex below).
// Origin: colourings of hyperbolic tilings after Vladimir Bulatov and Doug Dunham; the search after
// Charles Sims, "Computation with finitely presented groups"; see CREDITS.md.

import type { TriangleGroup } from "./groups.ts";

export type Perm = number[];

/** A colouring every symmetry of the tiling respects: one permutation per mirror. */
export interface MirrorColouring {
  kind?: "mirror";
  name: string;
  k: number;
  sigma: [Perm, Perm, Perm];
}

/** A colouring only the rotations respect: alpha for a = s1 s2 (about P), beta for b = s3 s1 (about
 *  Q). It colours kites (T and its mirror image across side 1). */
export interface ChiralColouring {
  kind: "chiral";
  name: string;
  k: number;
  alpha: Perm;
  beta: Perm;
}

export type Colouring = MirrorColouring | ChiralColouring;

/** The most colours a colouring may have: the shader packs a permutation in 3 bits a colour. */
export const MAX_COLOURS = 8;

export const identityPerm = (k: number): Perm => Array.from({ length: k }, (_, i) => i);

/** (a o b)(i) = a(b(i)) */
export function compose(a: Perm, b: Perm): Perm {
  return b.map((bi) => a[bi]);
}

export function power(a: Perm, n: number): Perm {
  let r = identityPerm(a.length);
  for (let i = 0; i < n; i++) r = compose(r, a);
  return r;
}

const isIdentity = (a: Perm) => a.every((v, i) => v === i);
const isPermOf = (s: Perm, k: number) => s.length === k && [...s].sort((a, b) => a - b).every((v, i) => v === i);

export function inversePerm(a: Perm): Perm {
  const out: Perm = new Array(a.length);
  a.forEach((v, i) => (out[v] = i));
  return out;
}

/** Why a colouring does not fit the group, or null when it does. */
export function validate(c: Colouring, g: Pick<TriangleGroup, "p" | "q" | "r">): string | null {
  if (c.kind === "chiral") {
    for (const [s, name] of [[c.alpha, "the turn about P"], [c.beta, "the turn about Q"]] as const)
      if (!isPermOf(s, c.k)) return `${name} is not a permutation of ${c.k} colours`;
    if (!isIdentity(power(c.alpha, g.p))) return `the colours do not close up around the corner with angle pi/p = pi/${g.p}`;
    if (!isIdentity(power(c.beta, g.q))) return `the colours do not close up around the corner with angle pi/q = pi/${g.q}`;
    if (!isIdentity(power(compose(c.alpha, c.beta), g.r))) return `the colours do not close up around the corner with angle pi/r = pi/${g.r}`;
    return null;
  }
  const [s1, s2, s3] = c.sigma;
  for (const [j, s] of c.sigma.entries()) {
    if (!isPermOf(s, c.k)) return `the map of mirror ${j + 1} is not a permutation of ${c.k} colours`;
    if (!isIdentity(compose(s, s))) return `mirror ${j + 1} must swap colours in pairs (its square is not the identity)`;
  }
  const checks: [Perm, Perm, number, string][] = [
    [s1, s2, g.p, "p"],
    [s1, s3, g.q, "q"],
    [s2, s3, g.r, "r"],
  ];
  for (const [a, b, m, name] of checks)
    if (!isIdentity(power(compose(a, b), m))) return `the colours do not close up around the corner with angle pi/${name} = pi/${m}`;
  return null;
}

/** The permutations a colouring's group is generated by. */
const generators = (c: Colouring): Perm[] => (c.kind === "chiral" ? [c.alpha, c.beta] : c.sigma);

/** True when every colour is used (the group moves colour 0 to every other colour). */
export function isTransitive(c: Colouring): boolean {
  const seen = new Set([0]);
  const queue = [0];
  const gens = generators(c);
  while (queue.length) {
    const i = queue.pop()!;
    for (const s of gens)
      if (!seen.has(s[i])) {
        seen.add(s[i]);
        queue.push(s[i]);
      }
  }
  return seen.size === c.k;
}

export const parity: MirrorColouring = { name: "Parity", k: 2, sigma: [[1, 0], [1, 0], [1, 0]] };

/** Two colours per polygon of {p, q}: mirrors through the polygon centre keep the colour, the edge
 *  mirror swaps it. Valid only for even q. */
export const faces2: MirrorColouring = { name: "Faces", k: 2, sigma: [[0, 1], [0, 1], [1, 0]] };

// ----------------------------------------------------------------------------- along a fold word

const pairCache = new WeakMap<ChiralColouring, Perm[][]>();

/** tau[i][j]: the permutation of the rotation r_i r_j (mirrors 0, 1, 2 for sides 1, 2, 3; tau[i][i] is
 *  the identity). With a = s1 s2 and b = s3 s1: s2 s1 = a^-1, s1 s3 = b^-1, s2 s3 = a^-1 b^-1, s3 s2 = b a. */
export function pairPerms(c: ChiralColouring): Perm[][] {
  const cached = pairCache.get(c);
  if (cached) return cached;
  const id = identityPerm(c.k);
  const ai = inversePerm(c.alpha);
  const bi = inversePerm(c.beta);
  const t = [
    [id, c.alpha, bi],
    [ai, id, compose(ai, bi)],
    [c.beta, compose(c.beta, c.alpha), id],
  ];
  pairCache.set(c, t);
  return t;
}

/** The colours the rotations give the kites when the identity's kite has colour 0: the orbit of 0
 *  under the permutations of the even words (a motif's tiles, math/motifs.ts). Each comes equally
 *  often, so their mean is the far tiles' colour. */
export function rotationOrbit(c: Colouring): number[] {
  const gens = c.kind === "chiral" ? [c.alpha, c.beta] : [compose(c.sigma[1], c.sigma[0]), compose(c.sigma[2], c.sigma[0])];
  const seen = [0];
  for (let i = 0; i < seen.length; i++)
    for (const g of gens) if (!seen.includes(g[seen[i]])) seen.push(g[seen[i]]);
  return seen.sort((a, b) => a - b);
}

/** The colour state after a fold word: the permutation, and for a chiral colouring the word's last
 *  mirror when its length is odd (-1 otherwise; always -1 for a mirror colouring). */
export interface Carried {
  perm: Perm;
  pending: number;
}

/** Continue the camera's permutation along a fold word (or a re-centering word, which is even). */
export function carry(c: Colouring, perm: Perm, word: readonly number[]): Carried {
  if (c.kind !== "chiral") {
    for (const j of word) perm = compose(perm, c.sigma[j]);
    return { perm, pending: -1 };
  }
  const tau = pairPerms(c);
  const even = word.length - (word.length % 2);
  for (let i = 0; i < even; i += 2) perm = compose(perm, tau[word[i]][word[i + 1]]);
  return { perm, pending: word.length % 2 ? word[word.length - 1] : -1 };
}

/** The colour of the folded point's tile: P(0), or for an odd chiral word (P o tau_e1)(0), the kite of
 *  h s1. */
export function colourOf(c: Colouring, s: Carried): number {
  if (c.kind !== "chiral" || s.pending < 0) return s.perm[0];
  return s.perm[pairPerms(c)[s.pending][0][0]];
}

/** The colour across side j of the folded point's triangle: (P o sigma_j)(0) for a mirror colouring;
 *  for a chiral one the same kite across side 1, and across sides 2 and 3 (P o tau_j1)(0) for an even
 *  word, (P o tau_ej)(0) for an odd one. */
export function colourAcross(c: Colouring, s: Carried, j: number): number {
  if (c.kind !== "chiral") return s.perm[c.sigma[j][0]];
  if (j === 0) return colourOf(c, s);
  const tau = pairPerms(c);
  return s.perm[(s.pending < 0 ? tau[j][0] : tau[s.pending][j])[0]];
}

// ----------------------------------------------------------------------------- search

/** Sims' low-index method: every transitive action of a finitely presented group on k points, point
 *  0 the start, in breadth-first normal form. Generator g's inverse is inv[g] (g itself for an
 *  involution); a relator is a word repeated m times. The images are defined one at a time, the first
 *  undefined (point, generator) in breadth-first order getting either a point already met or the next
 *  new one, and every relator is traced from every point as far as it is defined: a branch dies as
 *  soon as a cycle closes after a number of turns that does not divide m, or not at all. */
function lowIndex(k: number, inv: number[], rels: [number[], number][], found: (t: Int8Array[]) => void): void {
  const n = inv.length;
  const f = Array.from({ length: n }, () => new Int8Array(k).fill(-1));
  const consistent = (): boolean => {
    for (const [word, m] of rels)
      for (let x = 0; x < k; x++) {
        let y = x;
        let turns = 0;
        while (turns < m) {
          for (const g of word) {
            if (y < 0) break;
            y = f[g][y];
          }
          if (y < 0) break;
          turns++;
          if (y === x) break;
        }
        if (y < 0) continue;
        if (y !== x || m % turns !== 0) return false;
      }
    return true;
  };
  const rec = (used: number): void => {
    for (let x = 0; x < used; x++)
      for (let g = 0; g < n; g++) {
        if (f[g][x] >= 0) continue;
        const gi = inv[g];
        for (let y = 0; y <= used && y < k; y++) {
          if (y < used && f[gi][y] >= 0) continue;
          f[g][x] = y;
          f[gi][y] = x;
          if (consistent()) rec(y === used ? used + 1 : used);
          f[g][x] = -1;
          f[gi][y] = -1;
        }
        return;
      }
    if (used === k) found(f.map((row) => row.slice()));
  };
  rec(1);
}

/** The smallest breadth-first relabelling of an action over every start point (generators in order,
 *  each with its inverse when it has one): equal for actions that differ only by naming. Returns the
 *  form and the relabelled tables of the given generators. */
function canonicalForm(f: Int8Array[], inv: number[], keep: number[]): { form: number[]; tables: Perm[] } {
  const k = f[0].length;
  let best: { form: number[]; tables: Perm[] } | null = null;
  for (let s0 = 0; s0 < k; s0++) {
    const label = new Array<number>(k).fill(-1);
    const order = [s0];
    label[s0] = 0;
    for (let i = 0; i < order.length; i++)
      for (let g = 0; g < inv.length; g++) {
        const y = f[g][order[i]];
        if (label[y] < 0) {
          label[y] = order.length;
          order.push(y);
        }
      }
    const tables = keep.map((g) => order.map((x) => label[f[g][x]]));
    const form = order.flatMap((_, i) => tables.map((t) => t[i]));
    if (!best || less(form, best.form)) best = { form, tables };
  }
  return best!;
}

function less(a: number[], b: number[]): boolean {
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) return a[i] < b[i];
  return false;
}

/** One action per class, in canonical form, sorted by it. */
function classes(k: number, inv: number[], rels: [number[], number][], keep: number[]): Perm[][] {
  const seen = new Map<string, { form: number[]; tables: Perm[] }>();
  lowIndex(k, inv, rels, (f) => {
    const c = canonicalForm(f, inv, keep);
    const key = c.form.join(",");
    if (!seen.has(key)) seen.set(key, c);
  });
  return [...seen.values()].sort((a, b) => (less(a.form, b.form) ? -1 : less(b.form, a.form) ? 1 : 0)).map((c) => c.tables);
}

function involutions(k: number): Perm[] {
  const out: Perm[] = [];
  const rec = (p: Perm, i: number) => {
    if (i === k) return out.push([...p]);
    if (p[i] !== -1) return rec(p, i + 1);
    p[i] = i; // fixed point
    rec(p, i + 1);
    for (let j = i + 1; j < k; j++)
      if (p[j] === -1) {
        p[i] = j;
        p[j] = i;
        rec(p, i + 1);
        p[j] = -1;
      }
    p[i] = -1;
  };
  rec(new Array(k).fill(-1), 0);
  return out;
}

function permutations(k: number): Perm[] {
  if (k === 0) return [[]];
  const out: Perm[] = [];
  for (const p of permutations(k - 1))
    for (let i = 0; i <= p.length; i++) out.push([...p.slice(0, i), k - 1, ...p.slice(i)]);
  return out;
}

/** Up to 5 colours, version 1 named colourings by the order in which its search over involution
 *  triples met them first: each class is written as that first triple (the relabelling t o sigma o t^-1
 *  whose involutions come first in version 1's order) and the classes are sorted by it, so saved
 *  links keep their colours. */
const LEGACY_MAX = 5;

function legacyOrder(k: number, found: Perm[][]): Perm[][] {
  const index = new Map(involutions(k).map((s, i) => [s.join(","), i]));
  const relabels = permutations(k);
  const ranked = found.map((sigma) => {
    let best: { rank: number[]; sigma: Perm[] } | null = null;
    for (const t of relabels) {
      const ti = inversePerm(t);
      const s = sigma.map((x) => compose(t, compose(x, ti)));
      const rank = s.map((x) => index.get(x.join(","))!);
      if (!best || less(rank, best.rank)) best = { rank, sigma: s };
    }
    return best!;
  });
  return ranked.sort((a, b) => (less(a.rank, b.rank) ? -1 : less(b.rank, a.rank) ? 1 : 0)).map((r) => r.sigma);
}

const mirrorRels = (g: Pick<TriangleGroup, "p" | "q" | "r">): [number[], number][] => [
  [[0, 1], g.p],
  [[0, 2], g.q],
  [[1, 2], g.r],
];

/** Every transitive mirror colouring with 2 to maxK colours, one per relabelling class, fewest
 *  colours first: up to 5 colours in version 1's order and form (legacyOrder), then in canonical
 *  form. */
export function findColourings(g: Pick<TriangleGroup, "p" | "q" | "r">, maxK = MAX_COLOURS): MirrorColouring[] {
  const found: MirrorColouring[] = [];
  for (let k = 2; k <= maxK; k++) {
    let list = classes(k, [0, 1, 2], mirrorRels(g), [0, 1, 2]);
    if (k <= LEGACY_MAX) list = legacyOrder(k, list);
    for (const sigma of list) found.push({ name: "", k, sigma: sigma as [Perm, Perm, Perm] });
  }
  found.forEach((c, i) => (c.name = `Colouring ${i + 1} (${c.k} colours)`));
  return found;
}

/** Every transitive chiral colouring with 2 to maxK colours, one per relabelling class, fewest colours
 *  first, in canonical form. Generators a, a^-1, b, b^-1 with a^p = b^q = (ab)^r = 1. */
export function findChiralColourings(g: Pick<TriangleGroup, "p" | "q" | "r">, maxK = MAX_COLOURS): ChiralColouring[] {
  const found: ChiralColouring[] = [];
  const rels: [number[], number][] = [
    [[0], g.p],
    [[2], g.q],
    [[0, 2], g.r],
  ];
  for (let k = 2; k <= maxK; k++)
    for (const [alpha, beta] of classes(k, [1, 0, 3, 2], rels, [0, 2])) found.push({ kind: "chiral", name: "", k, alpha, beta });
  found.forEach((c, i) => (c.name = `Chiral ${i + 1} (${c.k} colours)`));
  return found;
}
